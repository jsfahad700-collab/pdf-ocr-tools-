def extract_headers(page_text: str, current_headers: dict, pdf_name: str = "") -> dict:
    headers = current_headers.copy()
    
    if "postcode" not in headers:
        headers["postcode"] = ""
    
    postcode_match = STRICT_POSTCODE_RE.search(page_text)
    if postcode_match:
        headers["postcode"] = postcode_match.group(1).strip()
    
    if "area_code" not in headers or not headers["area_code"]:
        if pdf_name:
            base_name = os.path.basename(pdf_name)
            filename_code_match = re.match(r'^(\d+)', base_name)
            headers["area_code"] = filename_code_match.group(1) if filename_code_match else ""
        else:
            headers["area_code"] = ""
            
    voter_area_pat = re.compile(r'(?:ভোটার\s+এলাকা(?:র)?\s*(?:নম্বর|নং|কোড))\s*[:ঃ\-—_=\s]*\s*([০-৯\d]+)', re.IGNORECASE)
    voter_area_match = voter_area_pat.search(page_text)
    voter_area_num = voter_area_match.group(1).strip() if voter_area_match else ""
    
    if pdf_name:
        pdf_name_lower = pdf_name.lower()
        female_indicators = ["মহিলা", "female", "mohila", "fem"]
        male_indicators = ["পুরুষ", "male", "purush"]
        if any(ind in pdf_name_lower for ind in female_indicators):
            headers["gender"] = "মহিলা"
        elif any(ind in pdf_name_lower for ind in male_indicators):
            headers["gender"] = "পুরুষ"
    
    for key, patterns in HEADER_REGEXES.items():
        for pattern in patterns:
            match = pattern.search(page_text)
            if match:
                val = match.group(1).strip()
                cleaned_val = clean_header_value(val)
                if cleaned_val:
                    if key != "post_office" and "_" in cleaned_val:
                        cleaned_val = cleaned_val.split("_", 1)[0].strip()
                    
                    if key == "post_office" and voter_area_num:
                        cleaned_val = f"{cleaned_val}_{voter_area_num}"
                    
                    if key == "ward":
                        cleaned_val = standardize_extracted_ward(cleaned_val)
                    
                    headers[key] = cleaned_val
                    break
                    
    header_area = page_text[:2500]
    
    female_keywords = ["মহিলা", "মিহলা", "মহলিা", "female", "mohila"]
    male_keywords = ["পুরুষ", "পুরূষ", "পুরুশ", "পুরুষ্", "male", "purush"]
    
    has_female = any(kw in header_area for kw in female_keywords)
    has_male = any(kw in header_area for kw in male_keywords)
    
    if has_female and not has_male:
        headers["gender"] = "মহিলা"
    elif has_male and not has_female:
        headers["gender"] = "পুরুষ"
            
    return headers

