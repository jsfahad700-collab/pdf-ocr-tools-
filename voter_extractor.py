# ---- দ্রুত সংস্করণ: প্যাটার্ন একবারই কম্পাইল, আর দরকারি অক্ষর না থাকলে ধাপটি বাদ ----
def _make_ftr(table):
    """ str.translate এর দ্রুত সমতুল্য: লেখায় যে অক্ষরগুলো আছে শুধু সেগুলোর জন্য str.replace চালায়
        (বড় ডিকশনারি দিয়ে translate ধীর)। ম্যাপের মান আবার ম্যাপের কী হলে (chain) সাধারণ translate-ই চলে। """
    tbl = {chr(k): v for k, v in table.items() if v != chr(k)}
    if any(c in tbl for v in tbl.values() for c in v):
        return lambda t: t.translate(table)
    keys = frozenset(tbl)

    def _f(t):
        for c in keys.intersection(t):
            t = t.replace(c, tbl[c])
        return t
    return _f


