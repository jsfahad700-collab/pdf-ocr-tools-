def _progress_init(q):
    global _PROG_Q
    _PROG_Q = q


def _report_progress(name, done, total):
    pct = 100 if total <= 0 else min(100, int(done * 100 / total))
    if _PROG_LAST.get(name) == pct:
        return
    _PROG_LAST[name] = pct
    try:
        if _PROG_Q is not None:
            _PROG_Q.put_nowait((name, pct))
        elif _PROG_CB is not None:
            _PROG_CB(name, pct)
    except Exception:
        pass



def process_pdf_worker(zip_path, pdf_name):
    records = []
    try:
        with zipfile.ZipFile(zip_path, 'r') as zf:
            pdf_bytes = zf.read(pdf_name)
            
        pdf_stream = io.BytesIO(pdf_bytes)
        reader = pypdf.PdfReader(pdf_stream)
        
        base_name = os.path.basename(pdf_name)
        filename_code_match = re.match(r'^(\d+)', base_name)
        pdf_code = filename_code_match.group(1) if filename_code_match else ""
        
        headers = {
            "upazila": "",
            "post_office": "",
            "ward": "",
            "gender": "",
            "area_code": pdf_code,
            "postcode": ""
        }
        
        total_pages = len(reader.pages)
        _report_progress(pdf_name, 0, total_pages)
        for page_idx, page in enumerate(reader.pages):
            _report_progress(pdf_name, page_idx, total_pages)
            page_text = page.extract_text()
            if not page_text:
                continue
            
            page_text = advanced_bangla_cleaner(page_text)
            
            page_text = _SIGN_RE.sub('', page_text)
            
            headers = extract_headers(page_text, headers, pdf_name)
            
            parts = ENTRY_SPLIT_RE.split(page_text)
            
            for block in parts[1:]:
                if block.strip():
                    if not is_record_cancelled(block):
                        record = parse_record_block_with_pats(block)
                        if record["name"] or record["voter_no"]:
                            full_record = {**record, **headers}
                            records.append(full_record)
                            
        _report_progress(pdf_name, total_pages, total_pages)
        pdf_stream.close()
    except Exception as e:
        logging.error(f"Error processing {pdf_name}: {str(e)}", exc_info=True)
        return pdf_name, [], str(e)
    finally:
        _GC_COUNT[0] += 1
        if _GC_COUNT[0] % 8 == 0:      # প্রতি PDF-এ নয়, কয়েকটা পরপর — সময় বাঁচে
            gc.collect()
        
    # ---- চূড়ান্ত পরিষ্কার (PDF-স্তরে) ----
    # (ক০) শব্দ-সংশোধন আরেকবার ফিল্ড-স্তরে: পার্সিং/লেবেল কাটার পরে যে রূপে লেখা দাঁড়ায় সেই রূপেও যেন ম্যাচ করে
    for rec in records:
        for _f in ("name", "father_name", "mother_name", "address", "profession"):
            _v = rec.get(_f)
            # শুধু সন্দেহজনক লেখায় চালানো হয় (ঠিক লেখায় বদল হয় না, আর সময়ও বাঁচে)
            if _v and (suspect_reasons(_v) or extra_reasons(_f, _v)):
                rec[_f] = post_fixes(_v)
    # (ক) ঠিকানার শেষে লেগে যাওয়া পেজ নম্বর বাদ (যেমন "... কিশোরগঞ্জ ২৯")
    for rec in records:
        addr = rec.get("address", "")
        if addr:
            addr = addr.replace("#", "").replace("\u25A1", "")   # # ও ফাঁকা বাক্স (□) = উৎস-ডাটার অকেজো অক্ষর
            addr = re.sub(r"^[\s,=*+\-./:;'\"]+", "", addr)
            rec["address"] = re.sub(r"(?<=[^\d\u09E6-\u09EF,\s])\s+[\u09E6-\u09EF0-9]{1,3}$", "", addr).strip()
    # (খ) post_office সব রেকর্ডে একই রূপে: "ডাকঘরের নাম_পোস্টকোড"
    _pcs = collections.Counter(r.get("postcode", "") for r in records if r.get("postcode"))
    if _pcs:
        _pc = _pcs.most_common(1)[0][0]
        for rec in records:
            po = rec.get("post_office", "")
            if po:
                rec["post_office"] = po.split("_")[0].strip() + "_" + _pc
    return pdf_name, records, None



