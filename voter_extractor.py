def _parse_tounicode(font_obj):
    bf = {}
    try:
        tu = font_obj["/ToUnicode"].get_object().get_data().decode("latin1")
    except Exception:
        return bf
    for blk in re.findall(r"beginbfchar(.*?)endbfchar", tu, re.S):
        for a, b in re.findall(r"<([0-9A-Fa-f]+)>\s*<([0-9A-Fa-f]+)>", blk):
            bf[int(a, 16)] = "".join(chr(int(b[i:i + 4], 16)) for i in range(0, len(b), 4))
    for blk in re.findall(r"beginbfrange(.*?)endbfrange", tu, re.S):
        for line in blk.strip().splitlines():
            m = re.match(r"\s*<([0-9A-Fa-f]+)>\s*<([0-9A-Fa-f]+)>\s*(.*)", line)
            if not m:
                continue
            a, b, rest = int(m.group(1), 16), int(m.group(2), 16), m.group(3).strip()
            if rest.startswith("["):
                for i, it in enumerate(re.findall(r"<([0-9A-Fa-f]+)>", rest)):
                    bf[a + i] = "".join(chr(int(it[j:j + 4], 16)) for j in range(0, len(it), 4))
            else:
                c = int(re.findall(r"<([0-9A-Fa-f]+)>", rest)[0], 16)
                for i in range(a, b + 1):
                    bf[i] = chr(c + i - a)
    return bf


def _draw_glyph(tt, gid):
    order = tt.getGlyphOrder()
    if gid < 0 or gid >= len(order):
        return None
    gs = tt.getGlyphSet()
    pen = _RecPen(gs)
    gs[order[gid]].draw(pen)
    contours, cur = [], []
    for op, args in pen.value:
        if op == "moveTo":
            cur = [args[0]]
        elif op == "lineTo":
            cur.append(args[0])
        elif op == "qCurveTo":
            pts = list(args)
            if pts[-1] is None:
                pts = pts[:-1]
            p0 = cur[-1] if cur else pts[0]
            for i in range(len(pts) - 1):
                c = pts[i]
                e = pts[-1] if i == len(pts) - 2 else ((c[0] + pts[i + 1][0]) / 2, (c[1] + pts[i + 1][1]) / 2)
                for t in (0.25, 0.5, 0.75, 1.0):
                    x = (1 - t) ** 2 * p0[0] + 2 * (1 - t) * t * c[0] + t * t * e[0]
                    y = (1 - t) ** 2 * p0[1] + 2 * (1 - t) * t * c[1] + t * t * e[1]
                    cur.append((x, y))
                p0 = e
        elif op in ("closePath", "endPath"):
            if len(cur) > 2:
                contours.append(cur)
            cur = []
    if not contours:
        return None
    allx = [p[0] for c in contours for p in c]
    ally = [p[1] for c in contours for p in c]
    minx, maxx, miny, maxy = min(allx), max(allx), min(ally), max(ally)
    w, h = max(maxx - minx, 1), max(maxy - miny, 1)
    sc = (_GLYPH_BOX - 20) / max(w, h)
    img = _Image.new("L", (_GLYPH_BOX, _GLYPH_BOX), 255)
    d = _ImageDraw.Draw(img)

    def area(c):
        return sum(c[i][0] * c[(i + 1) % len(c)][1] - c[(i + 1) % len(c)][0] * c[i][1] for i in range(len(c))) / 2

    pts = [[((x - minx) * sc + 10, _GLYPH_BOX - ((y - miny) * sc + 10)) for x, y in c] for c in contours]
    # সবচেয়ে বড় রেখার ঘূর্ণন-দিকই "ভরাট" ধরা হয়; উল্টো দিকের রেখা = ফাঁকা অংশ
    outer_sign = 1 if area(max(contours, key=lambda c: abs(area(c)))) > 0 else -1
    for c, raw in sorted(zip(pts, contours), key=lambda z: (area(z[1]) > 0) != (outer_sign > 0)):
        d.polygon(c, fill=0 if (area(raw) > 0) == (outer_sign > 0) else 255)
    return img


def glyph_images_from_pdf(pdf_bytes, chars):
    """ PDF এর ফন্ট থেকে প্রতিটি অজানা অক্ষরের গ্লিফ-ছবি বানায়: {অক্ষর: (gid, ছবি)} """
    out = {}
    if not HAVE_GLYPH_IMG:
        return out
    try:
        rd = pypdf.PdfReader(io.BytesIO(pdf_bytes))
        font_obj = tt = None
        for page in rd.pages:
            res = page.get("/Resources")
            fonts = res.get_object().get("/Font") if res else None
            if not fonts:
                continue
            for _, fv in fonts.get_object().items():
                fo = fv.get_object()
                try:
                    desc = fo["/DescendantFonts"][0].get_object()
                    data = desc["/FontDescriptor"].get_object()["/FontFile2"].get_object().get_data()
                    tt = _TTFont(io.BytesIO(data))
                    font_obj = fo
                    break
                except Exception:
                    continue
            if tt:
                break
        if not tt:
            return out
        inv = {u: cid for cid, u in _parse_tounicode(font_obj).items()}
        for ch in chars:
            gid = inv.get(ch, ord(ch) if ord(ch) < len(tt.getGlyphOrder()) else None)
            if gid is None:
                continue
            img = _draw_glyph(tt, gid)
            if img is not None:
                out[ch] = (gid, img)
    except Exception as e:
        logging.warning(f"গ্লিফ-ছবি বানানো যায়নি: {e}")
    return out


def build_glyph_sheet(glyphs, counts):
    """ glyphs: {ch: (gid, img)} → একটি PNG (bytes) """
    items = sorted(glyphs.items(), key=lambda kv: -counts.get(kv[0], 0))
    cols = 6
    rows = (len(items) + cols - 1) // cols
    cw, chh = _GLYPH_BOX + 10, _GLYPH_BOX + 34
    sheet = _Image.new("RGB", (cols * cw, rows * chh), "white")
    d = _ImageDraw.Draw(sheet)
    for i, (ch, (gid, img)) in enumerate(items):
        x, y = (i % cols) * cw, (i // cols) * chh
        sheet.paste(img.convert("RGB"), (x + 5, y + 26))
        d.rectangle([x + 2, y + 2, x + cw - 3, y + chh - 3], outline=(180, 180, 180))
        d.text((x + 8, y + 6), f"gid {gid}  U+{ord(ch):04X}  x{counts.get(ch, 0)}", fill=(0, 0, 0))
    buf = io.BytesIO()
    sheet.save(buf, "PNG")
    return buf.getvalue()



