_RX_UDA = re.compile(r'\bুদা\b')
_RX_ER = re.compile(r'(\S)\s+ের\b')


def fix_bengali_matra(text):
    if not text:
        return ""

    text = _FT_PROTECT(text)
    text = unicodedata.normalize("NFKC", text)
    if 's' in text:
        text = _RX_S.sub(r'নূ\1', text)
    text = text.replace("\x8c\x8a", "ন্দ্")     # চন্দ্র: ন্ + দ্ + র
    text = _FT_PRE(text)

    text = text.replace("শ্রীী", "শ্রী")
    if "শ্রীী" in text:
        text = _RX_SHREE.sub('শ্রী', text)

    text = _FT_PERSIAN(text)

    if 'ি' in text:
        text = _RX_PRE_I.sub(r'\1ি', text)
    if 'ে' in text:
        text = _RX_PRE_E.sub(r'\1ে', text)
    if 'ৈ' in text:
        text = _RX_PRE_AI.sub(r'\1ৈ', text)

    if 'Ï' in text:
        text = _RX_IO_A.sub(r'\1ো', text)
        text = _RX_IO.sub(r'\1ে', text)

    if 'ে' in text:      # মূল কোডে ছিল: ে+া → ো, ে+ৗ → ৌ (ব্যঞ্জনের পরে)
        text = _RX_O.sub('\\1\u09CB', text)
        text = _RX_AU.sub('\\1\u09CC', text)

    if 'Î' in text:
        text = _RX_REPH_V.sub(r'র্\1\2', text)
        text = _RX_REPH.sub(r'র্\1', text)
    if 'ু' in text:
        text = _RX_SP_U.sub('কু', text)
        text = _RX_ST_U.sub('কু', text)
        text = _RX_UDA.sub('কুদা', text)
    if 'ের' in text:
        text = _RX_ER.sub(r'\1ের', text)

    return text

