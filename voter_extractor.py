MAX_ZIP_UNCOMPRESSED = 2 * 1024 * 1024 * 1024   # জিপ-বম্ব সুরক্ষা: মোট আনকমপ্রেসড সর্বোচ্চ ২GB
MAX_ZIP_DEPTH = 5                                # ZIP-এর ভেতর ZIP কত স্তর পর্যন্ত


def _zip_member_name(info):
    """ ZIP-এ ফাইলের নাম UTF-8 ফ্ল্যাগ ছাড়া থাকলে সঠিকভাবে পড়ার চেষ্টা। """
    name = info.filename
    if not (info.flag_bits & 0x800):
        try:
            name = name.encode("cp437").decode("utf-8")
        except Exception:
            pass
    return name.replace("\\", "/")


def zip_pdf_plan(zip_path):
    """ (ভেতরে ZIP আছে কি না, সরাসরি পড়া যায় এমন PDF নামের তালিকা, দেখানোর নামের মানচিত্র) """
    with zipfile.ZipFile(zip_path) as zf:
        names = [(i.filename, _zip_member_name(i)) for i in zf.infolist() if not i.is_dir()]
    has_nested = any(d.lower().endswith(".zip") for _, d in names)
    pdfs = [(r, d) for r, d in names
            if d.lower().endswith(".pdf") and "__macosx" not in d.lower() and not os.path.basename(d).startswith("._")]
    pdfs.sort(key=lambda t: natural_key(t[1]))
    return has_nested, [r for r, _ in pdfs], {r: d for r, d in pdfs}


def flatten_zip(src_path, dst_path):
    """ src ZIP (এবং তার ভেতরের সব ZIP) থেকে সব .pdf বের করে একটি সমতল ZIP (dst) বানায়। """
    used = set()
    total = [0]
    count = [0]

    with zipfile.ZipFile(dst_path, "w", zipfile.ZIP_STORED) as out:

        def walk(zf, prefix, depth):
            for info in zf.infolist():
                if info.is_dir():
                    continue
                name = _zip_member_name(info)
                low = name.lower()
                base = os.path.basename(name)
                if "__macosx" in low or base.startswith("._") or not base:
                    continue
                total[0] += info.file_size
                if total[0] > MAX_ZIP_UNCOMPRESSED:
                    raise ValueError("ZIP এর আনকমপ্রেসড আকার অনেক বেশি (২GB এর বেশি)")
                if low.endswith(".pdf"):
                    arc = prefix + name
                    n = 1
                    while arc in used:
                        n += 1
                        arc = f"{prefix}{os.path.splitext(name)[0]}_{n}.pdf"
                    used.add(arc)
                    out.writestr(arc, zf.read(info))
                    count[0] += 1
                elif low.endswith(".zip") and depth < MAX_ZIP_DEPTH:
                    try:
                        with zipfile.ZipFile(io.BytesIO(zf.read(info))) as inner:
                            walk(inner, prefix + name + "/", depth + 1)
                    except (zipfile.BadZipFile, RuntimeError):
                        logging.warning(f"ভেতরের ZIP পড়া যায়নি: {name}")

        with zipfile.ZipFile(src_path) as zf:
            walk(zf, "", 0)
    return count[0]


