def finalize_text(text):
    """ গ্লিফ ম্যাপিংয়ের পরে যে কাঠামোগত ভুল (স্বরচিহ্নের ক্রম ইত্যাদি) থেকে যায় তা ঠিক করে। """
    if not text:
        return text
    # শুরুতে বসে থাকা (pre-posed) ি / ে / ৈ কে যুক্তবর্ণের পরে সরানো
    if "ি" in text:
        text = _RX_F1.sub(r"\1ি", text)
    if "ে" in text or "ৈ" in text:
        text = _RX_F2.sub(r"\2\1", text)
    # ে + া => ো,  ে + ৗ => ৌ
    if "ে" in text:
        text = _RX_F3.sub(r"\1ো", text)
        text = _RX_F4.sub(r"\1ৌ", text)
    # উদ্দিন / মুদ্দিন: দ্দ গ্লিফ ভুল করে ন্দ্র হয়ে গেলে
    if "ন্দ্র" in text:
        text = _RX_F5.sub(r"দ্দ\1", text)
    # হসন্তের ঠিক পরে স্বরচিহ্ন বৈধ নয় => অর্ধ-গ্লিফটি আসলে পূর্ণ অক্ষর (ধ্+ু → ধু)
    if "\u09CD" in text:
        text = _RX_F6.sub("", text)
    # ফন্টের ◌ প্লেসহোল্ডার বাদ; স্বরচিহ্নের পরে ভুল হসন্ত (খাতু◌্ন → খাতুন, পূ◌্র্ব → পূর্ব)
    text = text.replace("\u25CC", "")
    if "\u09CD" in text:
        text = _RX_F7.sub(r"\1", text)
    # মযি়া / মিযি়া → মিয়া  (য় + ি ভুল ক্রমে)
    if "\u09BC" in text:
        text = _RX_F8.sub("\\1\u09BF\u09AF\u09BC", text)
    # ফয়িা / ময়িা / দয়িা → ফিয়া / মিয়া / দিয়া  (ি + া কখনো পরপর বৈধ নয়)
    if "ি" in text:
        text = _RX_F9.sub("\\1\u09BF\\2", text)
    # শব্দের শুরুতে একা ু => কু
    if "ু" in text:
        text = _RX_F10.sub("\u0995\u09C1", text)
    for wrong, right in FINAL_FIXES.items():
        text = text.replace(wrong, right)
    # শব্দের মাঝে অর্ধ-অক্ষরের পর লেআউটের ফাঁকে ঢুকে যাওয়া স্পেস বাদ (পূর্ ব → পূর্ব)
    if "\u09CD" in text:
        text = _RX_F11.sub(r"\1", text)
        # শব্দের শুরুতে বা শেষে একা হসন্ত থাকা ভুল (মধত্য্ → মধ্য্ → মধ্য, ্আড়াইবাড়িয়া → আড়াইবাড়িয়া)
        text = _RX_F12.sub('', text)
        text = _RX_F13.sub('', text)
    # একই স্বরচিহ্ন পরপর দুইবার
    text = _RX_F14.sub(r"\1", text)
    return text

_OK_PUNCT = set(" .,:;-–—()/'\"_&ঃ।=*+#")

def suspect_reasons(text):
    """ কোনো টেক্সটে ভুল থাকার সম্ভাবনা থাকলে কারণগুলোর তালিকা ফেরত দেয় (রিপোর্টের জন্য)। """
    reasons = []
    if not text:
        return reasons
    for ch in text:
        o = ord(ch)
        if 0x0980 <= o <= 0x09FF or ch in _OK_PUNCT or ch.isdigit():
            continue
        reasons.append(f"অজানা অক্ষর '{ch}' (U+{o:04X})")
    if re.search(r"(?:^|\s)[\u0981-\u0983\u09BC\u09BE-\u09CD\u09D7]", text):
        reasons.append("শব্দের শুরুতে স্বরচিহ্ন/হসন্ত")
    if re.search("\u09CD(?:\\s|$)", text):
        reasons.append("শব্দের শেষে হসন্ত")
    if re.search(_NOT_CONS_BEFORE + "[িেৈ]", text):
        reasons.append("স্বরচিহ্ন ভুল জায়গায়")
    return list(dict.fromkeys(reasons))

